DROP TABLE IF EXISTS appointments;
DROP TABLE IF EXISTS availability_slots;
DROP TABLE IF EXISTS services;
DROP TABLE IF EXISTS providers;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    role VARCHAR(20) NOT NULL
);

CREATE TABLE providers (
    provider_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL UNIQUE REFERENCES users(user_id),
    bio TEXT,
    game_specialty VARCHAR(100)
);

CREATE TABLE services (
    service_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id INT NOT NULL REFERENCES providers(provider_id),
    service_name VARCHAR(100) NOT NULL,
    description TEXT,
    duration_minutes INT NOT NULL
);

CREATE TABLE availability_slots (
    slot_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id INT NOT NULL REFERENCES providers(provider_id),
    service_id INT NOT NULL REFERENCES services(service_id),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE appointments (
    appointment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(user_id),
    slot_id INT NOT NULL UNIQUE REFERENCES availability_slots(slot_id),
    status VARCHAR(20) NOT NULL DEFAULT 'BOOKED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
