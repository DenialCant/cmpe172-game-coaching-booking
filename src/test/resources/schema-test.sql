DROP TABLE IF EXISTS mock_notification_receipts;
DROP TABLE IF EXISTS notification_outbox;
DROP TABLE IF EXISTS appointments;
DROP TABLE IF EXISTS availability_slots;
DROP TABLE IF EXISTS services;
DROP TABLE IF EXISTS providers;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    role VARCHAR(20) NOT NULL
);

CREATE TABLE providers (
    provider_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL UNIQUE REFERENCES users(user_id),
    bio TEXT,
    game_specialty VARCHAR(100)
);

CREATE TABLE services (
    service_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id INT NOT NULL REFERENCES providers(provider_id),
    service_name VARCHAR(100) NOT NULL,
    description TEXT,
    duration_minutes INT NOT NULL
);

CREATE TABLE availability_slots (
    slot_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id INT NOT NULL REFERENCES providers(provider_id),
    service_id INT NOT NULL REFERENCES services(service_id),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE appointments (
    appointment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(user_id),
    slot_id INT NOT NULL REFERENCES availability_slots(slot_id),
    status VARCHAR(20) NOT NULL DEFAULT 'BOOKED',
    booked_slot_id INT GENERATED ALWAYS AS (CASE WHEN status = 'BOOKED' THEN slot_id ELSE NULL END),
    UNIQUE (booked_slot_id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- Durable fallback. Queued in the SAME transaction as the booking/cancellation.
CREATE TABLE IF NOT EXISTS notification_outbox (
    notification_id VARCHAR(100) PRIMARY KEY,
    recipient VARCHAR(320) NOT NULL,
    notification_type VARCHAR(40) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'DELIVERED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_notification_outbox_pending
    ON notification_outbox(status, created_at);

-- Receiver-owned state for the mock service. It deduplicates across restarts.
CREATE TABLE IF NOT EXISTS mock_notification_receipts (
    notification_id VARCHAR(100) PRIMARY KEY,
    recipient VARCHAR(320) NOT NULL,
    notification_type VARCHAR(40) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    accepted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
